print("1~100 能被3整除不能被5整除的数有:")
nums = []                         # 循环外：先准备一个空列表
for i in range( 1, 101 ):
    if i % 3 == 0 and i % 5 != 0:
            nums.append(i)        # 循环内：只做"收集"这一件事,nums.append(i) 是“把 i 加到列表末尾”，列表会越攒越长
print(nums)                       # 循环后：一次性打印